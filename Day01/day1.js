// 1. var
var name = "Krishnaveni";
console.log(name);

// Redeclaration
var name1 = "Veni";
var name1 = "Puneeth";
console.log(name1);

// 2. let
let trainer;
trainer = "30/10/2000";
console.log(trainer);

// Reassignment
trainer = "30/10/2001";
console.log(trainer);

// 3. const
const birthday = "22/11/2000";
console.log(birthday);

// const reassignment is not allowed
// birthday = "11/12/2000";

// 4. Difference between var, let and const
// var   - Redeclaration and reassignment allowed
// let   - Reassignment allowed
// const - Reassignment not allowed
